function createTranslator(locale = "en") {
  const lang = normalizeLocale(locale) || "en";
  const dict = MESSAGES[lang] || MESSAGES.en;
  return function t(key, params = {}) {
    const raw = dict[key] !== undefined ? dict[key] : MESSAGES.en[key] !== undefined ? MESSAGES.en[key] : key;
    return String(raw).replace(/\{([a-zA-Z0-9_]+)\}/g, (_m, k) =>
      params[k] !== undefined ? String(params[k]) : `{${k}}`
    );
  };
}

