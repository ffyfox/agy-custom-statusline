"use strict";

function normalizeLocale(value) {
  if (typeof value !== "string") return "";
  const lower = value.trim().toLowerCase();
  if (lower === "zh" || lower.startsWith("zh-") || lower.startsWith("zh_")) return "zh";
  if (lower === "en" || lower.startsWith("en-") || lower.startsWith("en_")) return "en";
  return "";
}

function resolveLocale({ cliLang, configLocale, env = process.env } = {}) {
  const fromCli = normalizeLocale(cliLang);
  if (fromCli) return fromCli;

  const fromEnv = normalizeLocale(env?.STATUSLINE_LANG);
  if (fromEnv) return fromEnv;

  if (typeof configLocale === "string" && configLocale.trim().toLowerCase() !== "auto") {
    const fromCfg = normalizeLocale(configLocale);
    if (fromCfg) return fromCfg;
  }

  const sysLang = env?.LC_ALL || env?.LC_MESSAGES || env?.LANG || "";
  if (/^zh/i.test(String(sysLang))) return "zh";
  return "en";
}

